import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { SceneModule, createBlankProject, createStarterProject, projectHasAuthoredContent } from "../js/model.js";

globalThis.Node = { TEXT_NODE: 3, ELEMENT_NODE: 1 };
globalThis.DOMParser = class {
  parseFromString() {
    return { body: { childNodes: [] } };
  }
};
globalThis.document = {
  createElement() {
    return { innerHTML: "", append() {} };
  },
  createTextNode(textContent) {
    return { nodeType: Node.TEXT_NODE, textContent };
  },
};

const blank = createBlankProject();
assert.equal(blank.title, "Nueva aventura");
assert.equal(blank.scenes.length, 1, "a new project begins with one editable scene");
assert.equal(blank.scenes[0].name, "Escena 1");
assert.equal(new SceneModule({ name: "Módulo 7" }).name, "Escena 7", "legacy autogenerated module names migrate to scene terminology");
assert.equal(new SceneModule({ name: "Módulo del puerto" }).name, "Módulo del puerto", "custom names are preserved during migration");
assert.equal(blank.scenes[0].stage.layers.length, 0, "the stage starts without images");
assert.equal(blank.scenes[0].dialogues.length, 0, "the scene starts without dialogues");
assert.equal(blank.scenes[0].decisions.choices.length, 0, "the scene starts without choices");
assert.equal(blank.scenes[0].decisions.prompt, "", "the decision prompt starts empty");
assert.equal(projectHasAuthoredContent(blank), false, "a fresh project must not trigger the save prompt");
assert.equal(projectHasAuthoredContent(createStarterProject()), true, "the starter project contains work to protect");
const renamed = createBlankProject();
renamed.title = "Mi aventura";
assert.equal(projectHasAuthoredContent(renamed), true, "a renamed project contains work to preserve");
const styled = createBlankProject();
styled.scenes[0].dialogueStyle.textColor = "#ffffff";
assert.equal(projectHasAuthoredContent(styled), true, "custom styling counts as project work");

